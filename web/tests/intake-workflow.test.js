import { test } from "node:test";
import assert from "node:assert/strict";
import { build } from "esbuild";
import { caseActions } from "../src/case-workflow.js";
const memory = () => { const values = new Map(); return { getItem:k=>values.get(k) || null, setItem:(k,v)=>values.set(k,v), removeItem:k=>values.delete(k) }; };
test("a new referral progresses to closure once, with one booking and role-owned milestones", async () => {
 globalThis.localStorage=memory(); globalThis.sessionStorage=memory();
 globalThis.fetch=()=>{ throw new Error("Browser simulation must not contact external systems"); };
 const bundle=await build({entryPoints:["src/gateway.js"],bundle:true,write:false,format:"esm",platform:"node",define:{"import.meta.env.DEV":"false"}});
 const g=await import("data:text/javascript;base64,"+Buffer.from(bundle.outputFiles[0].text).toString("base64"));
 const users=await g.request("/auth/demo-users"), coordinator=users.find(u=>u.role==="demo_admin"), clinician=users.find(u=>u.role==="clinician");
 await g.login(coordinator);
 const input={synthetic_fixture_id:7,external_reference:"SYN-EMAIL-TEST",procedure_code:"70551",location:"SYN-MRI-A",scenario:"missing_note"};
 const c=await g.request("/referrals",input);
 assert.equal(c.patient_name,"Lena Park"); assert.equal(c.scheduling_status,"NOT_SCHEDULED");
 assert.equal((await g.request("/referrals",input)).id,c.id);
 await assert.rejects(g.request("/referrals",{...input,synthetic_fixture_id:8}),/different content/);
 const event=event_type=>g.request("/demo/events",{case_id:c.id,event_type});
 await assert.rejects(g.request(`/cases/${c.id}/appointments/propose`,{}),/documents/);
 await event("document_received"); await event("authorization_approved");
 const proposal=await g.request(`/cases/${c.id}/appointments/propose`,{scheduled_at:new Date(Date.now()+86400000).toISOString(),location:"SYN-MRI-A"});
 assert.equal((await g.request(`/cases/${c.id}/appointments/propose`,{})).id,proposal.id);
 assert.deepEqual(caseActions(c,"demo_admin",[proposal],[]),[]);
 await g.request(`/approvals/${proposal.id}/approve`,{});
 await assert.rejects(g.request(`/cases/${c.id}/appointments/propose`,{}),/already has an appointment/);
 assert.deepEqual(caseActions(c,"demo_admin",[],[]),[]);
 await assert.rejects(g.request(`/cases/${c.id}/clinical-milestones`,{milestone:"PREVISIT_REVIEW",expected_version:c.version,synthetic_attestation:true}),/clinician/);
 await g.login(clinician);
 for(const milestone of ["PREVISIT_REVIEW","READY","SERVICE_COMPLETED"]) await g.request(`/cases/${c.id}/clinical-milestones`,{milestone,expected_version:c.version,synthetic_attestation:true});
 assert.equal((await g.request("/appointments")).filter(a=>a.case_id===c.id && a.status==="COMPLETED").length,1);
 assert.deepEqual(caseActions(c,"clinician",[],[]),[]);
 await g.login(coordinator);
 const doc=await g.request(`/cases/${c.id}/documents`,{fixture_type:"final_report"}); await g.request(`/documents/${doc.id}/verify`,{});
 await g.login(clinician);
 for(const milestone of ["REPORT_FINAL","COMMUNICATION_COMPLETE"]) await g.request(`/cases/${c.id}/clinical-milestones`,{milestone,expected_version:c.version,synthetic_attestation:true});
 await g.login(coordinator); await event("claim_submitted"); await event("claim_paid");
 const closure=await g.request(`/cases/${c.id}/closure/propose`,{disposition:"FULLY_RESOLVED"}); await g.request(`/approvals/${closure.id}/approve`,{});
 assert.equal(c.overall_status,"FULLY_RESOLVED"); assert.deepEqual(caseActions(c,"demo_admin",[],[]),[]);
 assert.equal((await g.request("/tasks")).filter(t=>t.case_id===c.id && t.status==="OPEN").length,0);
 assert.equal((await g.request("/appointments")).filter(a=>a.case_id===c.id).length,1);
 await assert.rejects(g.request(`/cases/${c.id}/closure/propose`,{disposition:"FULLY_RESOLVED"}),/already resolved/);
});
